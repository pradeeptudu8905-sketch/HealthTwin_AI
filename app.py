import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))

import streamlit as st
import pandas as pd
import plotly.express as px
from src.data import make_patient_timeline
from src.model import train_demo_model, estimate_risk, FEATURES

st.set_page_config(page_title="HealthTwin AI", page_icon="🩺", layout="wide")

@st.cache_resource
def load_model():
    return train_demo_model()

model, metrics, training_data = load_model()

st.title("🩺 HealthTwin AI")
st.caption("Healthcare Digital Twin • Educational proof-of-concept using synthetic data only")
st.warning("Demo only — not a medical diagnosis or treatment tool. All patient and sensor values are synthetic.")

with st.sidebar:
    st.header("Virtual patient")
    st.write("Adjust the synthetic patient's historical record and current wearable readings.")
    age = st.slider("Age", 18, 85, 52)
    prior_diabetes = st.selectbox("Previous diabetes diagnosis", [0, 1], format_func=lambda x: "No" if x == 0 else "Yes")
    hba1c = st.slider("Historical HbA1c (%)", 4.0, 11.5, 6.2, 0.1)
    glucose = st.slider("Current glucose (mg/dL)", 55, 320, 142)
    resting_hr = st.slider("Current/resting heart rate (bpm)", 42, 135, 78)
    sleep_hours = st.slider("Sleep in last 24h (hours)", 2.0, 12.0, 6.5, 0.5)
    steps = st.slider("Steps in last 24h", 100, 22000, 5200, 100)
    hrv = st.slider("Heart-rate variability (ms)", 8, 120, 42)

patient = {
    "age": age, "prior_diabetes": prior_diabetes, "hba1c": hba1c,
    "resting_hr": resting_hr, "glucose": glucose, "sleep_hours": sleep_hours,
    "steps": steps, "hrv": hrv
}
risk = estimate_risk(model, patient)

st.subheader("Virtual patient overview")
c1, c2, c3, c4 = st.columns(4)
c1.metric("Current glucose", f"{glucose} mg/dL")
c2.metric("Heart rate", f"{resting_hr} bpm")
c3.metric("Sleep", f"{sleep_hours:.1f} h")
c4.metric("Steps", f"{steps:,}")

left, right = st.columns([1.15, 1])
with left:
    st.subheader("Wearable stream — last 24 hours")
    timeline = make_patient_timeline(patient)
    fig = px.line(timeline, x="time", y="glucose", markers=True,
                  title="Simulated glucose trend", labels={"time":"Time", "glucose":"Glucose (mg/dL)"})
    fig.update_layout(height=330, margin=dict(l=10, r=10, t=50, b=10))
    st.plotly_chart(fig, use_container_width=True)
    fig2 = px.line(timeline, x="time", y="heart_rate", title="Simulated heart-rate trend",
                   labels={"time":"Time", "heart_rate":"Heart rate (bpm)"})
    fig2.update_layout(height=280, margin=dict(l=10, r=10, t=50, b=10))
    st.plotly_chart(fig2, use_container_width=True)

with right:
    st.subheader("AI risk estimate")
    st.metric("Estimated probability of simulated elevated-glucose event in next 2 hours", f"{risk:.0%}")
    if risk >= 0.65:
        st.error("Higher estimated risk in this demo. Review the inputs and seek qualified clinical assessment when appropriate.")
    elif risk >= 0.35:
        st.warning("Intermediate estimated risk in this demo. This is a model output, not a diagnosis.")
    else:
        st.success("Lower estimated risk in this demo. A low score does not rule out a health problem.")
    st.progress(min(max(risk, 0.0), 1.0))
    st.markdown("**Historical record used**")
    st.write({
        "Age": age,
        "Previous diabetes diagnosis": "Yes" if prior_diabetes else "No",
        "Historical HbA1c": f"{hba1c:.1f}%",
        "Source": "Synthetic demo profile"
    })
    st.markdown("**How the Digital Twin works**")
    st.write("Historical record + simulated sensor stream → machine-learning model → risk estimate → clinician-facing dashboard.")
    st.markdown("**Model sanity check**")
    
    st.markdown("**Model evaluation — held-out synthetic test set**")

    m1, m2 = st.columns(2)
    m1.metric("Accuracy", f"{metrics['accuracy']:.3f}")
    m2.metric("ROC-AUC", f"{metrics['roc_auc']:.3f}")

    m3, m4 = st.columns(2)
    m3.metric("Precision", f"{metrics['precision']:.3f}")
    m4.metric("Recall", f"{metrics['recall']:.3f}")

    st.metric("F1-score", f"{metrics['f1']:.3f}")

    st.markdown("**Confusion matrix**")
    cm = pd.DataFrame(
        metrics["confusion_matrix"],
        index=["Actual: No event", "Actual: Event"],
        columns=["Predicted: No event", "Predicted: Event"],
    )
    st.dataframe(cm, use_container_width=True)

    st.caption(
        "All metrics are calculated on a held-out synthetic test set. "
        "They do not demonstrate clinical accuracy or real-world "
        "medical effectiveness."
    )

    st.caption("This metric only measures performance on simulated data generated by the same toy process. It is not evidence of clinical performance.")

st.divider()
st.subheader("Model feature importance")
importance = pd.DataFrame({"Feature": FEATURES, "Importance": model.feature_importances_}).sort_values("Importance", ascending=True)
fig3 = px.bar(importance, x="Importance", y="Feature", orientation="h",
              title="Which inputs influenced the model most (synthetic training data)?")
fig3.update_layout(height=330, margin=dict(l=10, r=10, t=50, b=10))
st.plotly_chart(fig3, use_container_width=True)

with st.expander("Data and ethical limitations"):
    st.write("""
    - Every record and time-series reading in this starter project is synthetic.
    - The event labels are generated using a transparent simulation rule, not clinical outcomes.
    - Risk probabilities and thresholds are illustrative only.
    - Do not enter real patient information or use this app to make medical decisions.
    - A credible research version would need expert-defined outcomes, appropriately governed data,
      external validation, calibration, bias assessment, privacy controls, and clinical oversight.
    """)
